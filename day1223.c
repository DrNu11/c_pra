#include <stdio.h>

// 函数功能：在原字符串中删除指定字符，不使用额外数组
void delete_char(char *str, char target) {
    // 1. 定义“读指针”：负责在前面探路，遍历每一个字符
    // 初始化时指向字符串的开头
    char *read_ptr = str; 

    // 2. 定义“写指针”：负责跟在后面，只记录“有效”的字符
    // 初始化时也指向字符串的开头
    char *write_ptr = str;

    // 3. 开始循环：只要读指针没有遇到字符串结束符 '\0'，就一直循环
    while (*read_ptr != '\0') {
        
        // 4. 核心逻辑判断：检查当前读到的字符(*read_ptr)是不是我们要删的那个(target)
        if (*read_ptr != target) {
            
            // 5. 如果不是垃圾字符（是有效数据）：
            // 把它“抄写”到写指针当前的位置
            // 注意：刚开始时 read和write 指向同一个位置，自己抄给自己，没影响
            // 但一旦遇到过垃圾字符，write就会落后于read，这时就是把后面的数据往前挪
            *write_ptr = *read_ptr;

            // 6. 抄写完一个有效字符后，写指针向后移动一位
            // 准备接收下一个有效字符
            write_ptr++;
        }

        // 7. 无论刚才那个字符是要保留还是删除
        // 读指针都要无条件向后移动一位，去检查下一个字符
        read_ptr++;
    }

    // 8. 循环结束了，所有字符都检查完了
    // 此时 write_ptr 停在有效字符串的末尾后面
    // 必须手动给这里加上字符串结束符 '\0'，告诉系统字符串到此为止
    // 否则打印时会出现乱码
    *write_ptr = '\0';
}

int main() {
    // 定义测试字符串，这里模拟包含噪声 '#' 的数据
    // 注意：这里必须用数组形式 []，不能用 char *p = "..."，因为常量字符串不可修改
    char buffer[] = "Temp:#24.5#C; Hum:#60#%";
    
    // 定义要删除的目标字符
    char target = '#';

    printf("处理前: %s\n", buffer);

    // 调用函数，传入数组名（即首地址）和目标字符
    delete_char(buffer, target);

    printf("处理后: %s\n", buffer);

    return 0;
}